import {test,before,after} from 'node:test';
import assert from 'node:assert/strict';
import request from 'supertest';
import mongoose from 'mongoose';
import {MongoMemoryServer} from 'mongodb-memory-server';
import {createApp} from '../src/app.js';
import Project from '../src/models/Project.js';
import Unit from '../src/models/Unit.js';
const key='test-secret-key-32-characters-long-only';
const app=createApp({adminKey:key,origins:['http://localhost:5173']});
const auth={Authorization:`Bearer ${key}`};
const body={name:'نساج اختبار',slug:'nesaj-test',city:'الدمام',type:'villa',status:'ready',priceFrom:1200000,totalUnits:6,image:'https://example.com/image.jpg',description:'Test project',location:{address:'Test',latitude:26,longitude:50},features:['Garden']};
let db;
before(async()=>{db=await MongoMemoryServer.create();await mongoose.connect(db.getUri());await Project.init();await Unit.init();});
after(async()=>{await mongoose.disconnect();await db?.stop();});
test('Complete API lifecycle, security, validation, filtering and referential checks',async()=>{
 await request(app).get('/api/inquiries').expect(401);
 await request(app).post('/api/projects').send(body).expect(401);
 await request(app).get('/api/projects').set('Origin','https://evil.example').expect(403);
 const cors=await request(app).options('/api/projects').set('Origin','http://localhost:5173').set('Access-Control-Request-Method','POST').expect(204);
 assert.equal(cors.headers['access-control-allow-origin'],'http://localhost:5173');
 await request(app).post('/api/projects').set(auth).send({...body,priceFrom:-1}).expect(400);
 const created=await request(app).post('/api/projects').set(auth).send(body).expect(201);
 const id=created.body.data._id;
 await request(app).post('/api/projects').set(auth).send(body).expect(409);
 const found=await request(app).get('/api/projects').query({city:'الدمام',type:'villa',status:'ready',name:'نساج'}).expect(200);
 assert.equal(found.body.pagination.total,1);
 const literal=await request(app).get('/api/projects').query({name:'.*'}).expect(200);assert.equal(literal.body.pagination.total,0);
 await request(app).get('/api/projects').query({'city[$ne]':'x'}).expect(400);
 await request(app).get('/api/projects?page=0').expect(400);
 await request(app).get('/api/projects/nesaj-test').expect(200);
 await request(app).get('/api/projects/bad/units').expect(400);
 await request(app).get('/api/projects/aaaaaaaaaaaaaaaaaaaaaaaa/units').expect(404);
 await Unit.create({projectId:id,unitNumber:'1',type:'villa',area:250,price:1200000,bedrooms:5,bathrooms:4});
 const units=await request(app).get(`/api/projects/${id}/units`).expect(200);assert.equal(units.body.data.length,1);
 await request(app).post('/api/inquiries').send({name:'Mostafa',phone:'+966500000000',projectId:id,message:'Inquiry'}).expect(201);
 await request(app).post('/api/inquiries').send({name:'Mostafa',phone:'invalid',projectId:id,message:'Inquiry'}).expect(400);
 await request(app).post('/api/inquiries').send({name:'Mostafa',phone:'+966500000000',projectId:'aaaaaaaaaaaaaaaaaaaaaaaa',message:'Inquiry'}).expect(404);
 const inquiries=await request(app).get('/api/inquiries').set(auth).expect(200);assert.equal(inquiries.body.data[0].projectId.slug,'nesaj-test');
 const updated=await request(app).put(`/api/projects/${id}`).set(auth).send({priceFrom:1400000}).expect(200);assert.equal(updated.body.data.priceFrom,1400000);assert.deepEqual(updated.body.data.features,['Garden']);
 await request(app).put(`/api/projects/${id}`).set(auth).send({$set:{priceFrom:1}}).expect(400);
 await request(app).delete(`/api/projects/${id}`).set(auth).expect(409);
 const empty=await request(app).post('/api/projects').set(auth).send({...body,slug:'empty'}).expect(201);
 await request(app).delete(`/api/projects/${empty.body.data._id}`).set(auth).expect(204);
 await request(app).get('/api/projects/empty').expect(404);
});
